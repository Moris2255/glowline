const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  spawn: (o) => ipcRenderer.invoke('pty:spawn', o),
  write: (id, d) => ipcRenderer.send('pty:write', id, d),
  resize: (id, c, r) => ipcRenderer.send('pty:resize', id, c, r),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  onData: (cb) => ipcRenderer.on('pty:data', (_e, id, d) => cb(id, d)),
  onExit: (cb) => ipcRenderer.on('pty:exit', (_e, id, c) => cb(id, c)),
  onStat: (cb) => ipcRenderer.on('stat', (_e, s) => cb(s)),
  onVollbild: (cb) => ipcRenderer.on('vollbild', (_e, an) => cb(an)),
  onStatus: (cb) => ipcRenderer.on('status', (_e, s) => cb(s)),
  models: () => ipcRenderer.invoke('models:list'),
  loadModel: (id, laden) => ipcRenderer.invoke('models:load', id, laden),
  download: (d) => ipcRenderer.send('download:start', d),
  downloadCancel: (key) => ipcRenderer.send('download:cancel', key),
  onDownload: (cb) => ipcRenderer.on('download', (_e, p) => cb(p)),
  hfSearch: (q) => ipcRenderer.invoke('hf:search', q),
  tools: () => ipcRenderer.invoke('tools:check'),
  konten: () => ipcRenderer.invoke('konten:status'),
  kontoSetzen: (id, wert) => ipcRenderer.invoke('konten:setzen', id, wert),
  link: (url) => ipcRenderer.send('link:oeffnen', url),
  chat: (a) => ipcRenderer.send('chat:senden', a),
  chatStopp: (id) => ipcRenderer.send('chat:stopp', id),
  onChat: (cb) => ipcRenderer.on('chat', (_e, p) => cb(p)),
  lmStart: () => ipcRenderer.invoke('lmstudio:start'),
  studio: () => ipcRenderer.invoke('studio:status'),
  studioEinrichten: () => ipcRenderer.send('studio:einrichten'),
  studioModell: (id) => ipcRenderer.send('studio:modell', id),
  studioAbbrechen: (v) => ipcRenderer.send('studio:abbrechen', v),
  studioAuftrag: (a) => ipcRenderer.send('studio:auftrag', a),
  studioGalerie: () => ipcRenderer.invoke('studio:galerie'),
  studioWaehle: (art) => ipcRenderer.invoke('studio:waehle', art),
  studioFreigeben: (f) => ipcRenderer.send('studio:freigeben', f),
  studioZeigen: (f) => ipcRenderer.send('studio:zeigen', f),
  studioWegwerfen: (f) => ipcRenderer.invoke('studio:wegwerfen', f),
  onStudio: (cb) => ipcRenderer.on('studio', (_e, p) => cb(p)),
  pfadVon: (datei) => webUtils.getPathForFile(datei),
  hfFiles: (repo) => ipcRenderer.invoke('hf:files', repo),
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (p) => ipcRenderer.invoke('config:set', p),
  pickDir: (s) => ipcRenderer.invoke('dir:pick', s),
  clipRead: () => ipcRenderer.invoke('clip:read'),
  clipWrite: (t) => ipcRenderer.send('clip:write', t),
  setTitle: (t) => ipcRenderer.send('win:title', t),
  onConfig: (cb) => ipcRenderer.on('config', (_e, c) => cb(c)),
  einrichtungSystem: () => ipcRenderer.invoke('einrichtung:system'),
  einrichtungPlan: (w) => ipcRenderer.invoke('einrichtung:plan', w),
  einrichtungStart: (w) => ipcRenderer.invoke('einrichtung:start', w),
  einrichtungStand: () => ipcRenderer.invoke('einrichtung:stand'),
  einrichtungAbbrechen: () => ipcRenderer.send('einrichtung:abbrechen'),
  onEinrichtung: (cb) => ipcRenderer.on('einrichtung', (_e, s) => cb(s)),
});
